// Generates one Storybook API reference page per metadata record per framework
// (Spec B4-R3, ADR-058 DOC-3): packages/<fw>/src/<dir>/<dir>.api.mdx.
// Output is deterministic: record order, then the record's own prop/event order.
// `--check` writes nothing and exits 1 when a committed page differs.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { FRAMEWORKS, REPO_ROOT, readSourceMap } from "./check-api-drift.mjs";

const GENERATOR = "packages/component-metadata/scripts/generate-api-docs.mjs";

// Keeps metadata text literal in MDX list items (no JSX expressions, tags,
// emphasis, code or links), spelled the way Prettier prints it: numeric
// character references, `\*`, and `\_` except between two word characters.
const MDX_SPECIAL = /[\\{}<>|[\]#`]/g;

function escapeMdx(text) {
  return String(text)
    .replace(MDX_SPECIAL, (char) => `&#${char.charCodeAt(0)};`)
    .replace(/\*/g, "\\*")
    .replace(/_/g, (char, offset, all) =>
      /\w/.test(all[offset - 1] ?? "") && /\w/.test(all[offset + 1] ?? "") ? char : "\\_"
    );
}

function propLine(prop) {
  const facts = [
    `type ${escapeMdx(prop.type)}`,
    prop.required ? "required" : "optional",
    ...(prop.default === undefined ? [] : [`default ${escapeMdx(prop.default)}`]),
  ];
  const description = prop.description ? `: ${escapeMdx(prop.description)}` : "";
  return `- **${escapeMdx(prop.name)}** (${facts.join(", ")})${description}`;
}

function eventLine(event) {
  const payload = event.payloadDescription ? `: ${escapeMdx(event.payloadDescription)}` : "";
  return `- **${escapeMdx(event.frameworkName)}** (${event.mechanism}, semantic id ${escapeMdx(event.semanticId)})${payload}`;
}

function section(title, lines) {
  return [`## ${title}`, "", ...(lines.length > 0 ? lines : ["None."]), ""];
}

export function renderApiPage(record, framework) {
  const api = record.api?.[framework] ?? { props: [], events: [] };
  const pkg = record.packages[framework];
  return [
    `{/* Generated by ${GENERATOR} from the @ultimate/component-metadata ${escapeMdx(record.name)} record. Do not edit; run pnpm --filter @ultimate/component-metadata run docs:generate. */}`,
    "",
    'import { Meta } from "@storybook/addon-docs/blocks";',
    "",
    `<Meta title="API/${record.name}" />`,
    "",
    `# ${escapeMdx(record.name)} API`,
    "",
    escapeMdx(record.description),
    "",
    `- Package: ${escapeMdx(pkg.packageName)}`,
    `- Source: ${escapeMdx(pkg.sourcePath)}`,
    `- Category: ${escapeMdx(record.category)}`,
    "",
    ...section("Props", api.props.map(propLine)),
    ...section("Events", api.events.map(eventLine)),
  ].join("\n");
}

export function apiPagePath(framework, sourcePaths) {
  const dir = sourcePaths[0].split("/")[3];
  return resolve(REPO_ROOT, `packages/${framework}/src/${dir}/${dir}.api.mdx`);
}

export function plannedPages(records, sourceMap) {
  return records.flatMap((record) =>
    FRAMEWORKS.filter((framework) => record.api?.[framework]).map((framework) => ({
      path: apiPagePath(framework, sourceMap[record.name][framework]),
      contents: renderApiPage(record, framework),
    }))
  );
}

// Writes each out-of-date page, or with `check` only reports it. Prints the
// result and returns the process exit code.
export function syncApiPages(pages, check, repoRoot = REPO_ROOT) {
  const stale = [];
  for (const page of pages) {
    const current = existsSync(page.path) ? readFileSync(page.path, "utf8") : undefined;
    if (current === page.contents) continue;
    if (check) stale.push(relative(repoRoot, page.path));
    else writeFileSync(page.path, page.contents);
  }
  if (stale.length > 0) {
    for (const path of stale) console.error(`[docs] out of date: ${path}`);
    console.error(
      "[docs] FAILED: run pnpm --filter @ultimate/component-metadata run docs:generate"
    );
    return 1;
  }
  console.log(`[docs] OK: ${pages.length} API page(s) up to date`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { ALL_COMPONENTS } = await import("../dist/index.mjs");
  const pages = plannedPages(ALL_COMPONENTS, readSourceMap());
  process.exit(syncApiPages(pages, process.argv.includes("--check")));
}
